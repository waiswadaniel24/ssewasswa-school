-- ─── LICENSES TABLE ───────────────────────────────────────────────
-- Used by /api/pesapal-webhook to store license keys after payment.
CREATE TABLE IF NOT EXISTS licenses (
  id BIGSERIAL PRIMARY KEY,
  hwid TEXT NOT NULL UNIQUE,                                  -- hardware ID (browser fingerprint or Electron HWID)
  email TEXT NOT NULL,
  customer_name TEXT,
  license_key TEXT NOT NULL,
  tier TEXT NOT NULL CHECK (tier IN ('ORD', 'PREM', 'DEV')),
  amount_paid INTEGER DEFAULT 0,
  payment_reference TEXT,                                     -- Pesapal order tracking ID
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  activated_at TIMESTAMPTZ
);

COMMENT ON TABLE licenses IS 'License keys generated by Pesapal webhook after successful payment';

-- Indexes for fast lookups
CREATE INDEX IF NOT EXISTS licenses_email_idx ON licenses (email);
CREATE INDEX IF NOT EXISTS licenses_license_key_idx ON licenses (license_key);
CREATE INDEX IF NOT EXISTS licenses_hwid_idx ON licenses (hwid);

-- Enable Row Level Security (so only the service_role can write/read fully)
ALTER TABLE licenses ENABLE ROW LEVEL SECURITY;

-- Drop existing policies (idempotent — safe to re-run)
DROP POLICY IF EXISTS "Service role can manage licenses" ON licenses;
DROP POLICY IF EXISTS "Anyone can verify a license by key" ON licenses;
DROP POLICY IF EXISTS "Anyone can lookup by email" ON licenses;

-- Service role (used by /api/pesapal-webhook serverless function) has full access
CREATE POLICY "Service role can manage licenses"
  ON licenses FOR ALL
  TO service_role
  USING (true) WITH CHECK (true);

-- Allow anon read by license_key (for client-side license verification)
CREATE POLICY "Anyone can verify a license by key"
  ON licenses FOR SELECT
  TO anon, authenticated
  USING (true);

-- ─── AUDIT LOG TABLE (optional — for tracking webhook calls) ──────
CREATE TABLE IF NOT EXISTS pesapal_ipn_log (
  id BIGSERIAL PRIMARY KEY,
  received_at TIMESTAMPTZ DEFAULT NOW(),
  payment_reference TEXT,
  status TEXT,
  amount INTEGER,
  email TEXT,
  raw_payload JSONB
);

ALTER TABLE pesapal_ipn_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Service role can log IPN" ON pesapal_ipn_log;
CREATE POLICY "Service role can log IPN"
  ON pesapal_ipn_log FOR ALL
  TO service_role
  USING (true) WITH CHECK (true);

